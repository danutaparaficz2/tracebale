"""
supsi_kb.py - TRACEABLE Knowledge Base & Rule Engine
Bridges Computer Vision / VLM extraction with SUPSI's WBS, RSL, and Anomalies Catalog.
Reads JSON files generated by vLLM.py, optionally runs metric size estimation,
and exports standardized SUPSI inventory tables.
"""

import argparse
from dataclasses import dataclass, asdict
import json
import os
from pathlib import Path
import re
import sqlite3
from typing import Dict, List, Optional, Tuple, Any

import pandas as pd


HERE = Path(__file__).resolve().parent
DB_PATH = HERE / "supsi_kb.sqlite"
CURRENT_YEAR = 2026


# ---------------------------------------------------------------------------
# Database Initialization & Excel Ingestion
# ---------------------------------------------------------------------------
def init_db(
    anomalie_path: str = "120914_ListaAnomalieCompleta.xlsx",
    rsl_path: str = "130416_ListaRSL.xlsm",
    force_rebuild: bool = False
):
    """Parses SUPSI Excel tables and compiles them into a fast, indexed SQLite database."""
    if DB_PATH.exists() and not force_rebuild:
        return

    print("Building SUPSI Knowledge Base SQLite database...")
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS rsl_catalog (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nome_file TEXT,
            codice_wbs TEXT,
            nome_foglio TEXT,
            rsl_anni INTEGER
        )
    """)
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_rsl_wbs ON rsl_catalog(codice_wbs);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_rsl_foglio ON rsl_catalog(nome_foglio);")

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS anomalie_catalog (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nome_file TEXT,
            nome_foglio TEXT,
            codice_wbs TEXT,
            gravita TEXT,
            nome_anomalia TEXT,
            descrizione TEXT,
            parametro_misura TEXT,
            comportamento TEXT,
            codice_anomalia TEXT,
            rsl INTEGER
        )
    """)
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_anom_wbs ON anomalie_catalog(codice_wbs);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_anom_foglio ON anomalie_catalog(nome_foglio);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_anom_nome ON anomalie_catalog(nome_anomalia);")

    if Path(rsl_path).exists():
        df_rsl = pd.read_excel(rsl_path)
        df_rsl = df_rsl.rename(columns={
            "NOME FILE": "nome_file",
            "CODICE WBS": "codice_wbs",
            "NOME FOGLIO": "nome_foglio",
            "RSL COMPONENTE [anni]": "rsl_anni"
        })
        df_rsl[["nome_file", "codice_wbs", "nome_foglio", "rsl_anni"]].to_sql(
            "rsl_catalog", conn, if_exists="append", index=False
        )

    if Path(anomalie_path).exists():
        df_anom = pd.read_excel(anomalie_path, header=None)
        df_anom.columns = [
            "nome_file", "nome_foglio", "codice_wbs", "gravita",
            "nome_anomalia", "descrizione", "parametro_misura",
            "comportamento", "codice_anomalia", "rsl"
        ]
        df_anom.to_sql("anomalie_catalog", conn, if_exists="append", index=False)

    conn.commit()
    conn.close()
    print("SUPSI Knowledge Base ready.")


# ---------------------------------------------------------------------------
# Data Models
# ---------------------------------------------------------------------------
@dataclass
class AnomalyEvaluation:
    observed_defect: str
    matched_anomalia_name: Optional[str]
    codice_anomalia: Optional[str]
    severity: str
    severity_label: str
    description: Optional[str]


@dataclass
class ComponentCircularityReport:
    image_stem: str
    component_id: str
    component_name: str
    matched_foglio: str
    codice_wbs: str
    theoretical_rsl: int
    installation_year: Optional[int]
    age_years: Optional[int]
    residual_service_life: Optional[int]
    reuse_tier_evaluation: str
    anomalies: List[AnomalyEvaluation]
    ebkp_h_first: Optional[str] = None
    ebkp_h_second: Optional[str] = None
    ebkp_h_third: Optional[str] = None
    geometry: Optional[str] = None
    geometry_metric_measured: Optional[Dict[str, float]] = None
    aesthetics: Optional[str] = None
    functionality: Optional[str] = None
    pollutants: Optional[str] = None
    connection_type: Optional[str] = None
    disassembly_difficulty: Optional[str] = None
    bounding_box_2d: Optional[List[int]] = None

    def to_dict(self):
        return asdict(self)


# ---------------------------------------------------------------------------
# Rule Engine
# ---------------------------------------------------------------------------
class SupsiRuleEngine:
    RAW_COMPONENT_MAP: Dict[str, str] = {
        "portainternametallo": "PortaInternaMetallo",
        "flush steel fire-rated door leaf": "PortaInternaMetallo",
        "flush steel door": "PortaInternaMetallo",
        "steel fire-rated door": "PortaInternaMetallo",
        "steel door": "PortaInternaMetallo",
        "ei 60 internal door": "PortaInternaMetallo",
        "ei 30 internal door": "PortaInternaMetallo",
        "g0105_porta_interna": "PortaInternaMetallo",
        "internal door": "PortaInternaMetallo",
        "portainternalegno": "PortaInternaLegno",
        "wooden internal door": "PortaInternaLegno",
        "portainternavetro": "PortaInternaVetro",
        "glass internal door": "PortaInternaVetro",
        "finestrapvc": "SerramentoPVC",
        "double-glazed window with pvc frame": "SerramentoPVC",
        "pvc window": "SerramentoPVC",
        "e0301_finestra": "SerramentoPVC",
        "external glass door": "PorteEsterneMetallo",
        "e0303_portone_esterno": "PorteEsterneMetallo",
        "external steel staircase": "ScaleEstAcciaio",
        "i0204_scala_rampa": "ScaleEstAcciaio",
        "cast-iron radiator": "Radiatori",
        "radiator": "Radiatori",
        "d0505_diffusione_di_calore": "Radiatori",
        "gas condensing boiler": "CTGruppoTermico",
        "d0502_produzione_di_calore": "CTGruppoTermico",
        "steel column (hea 260)": "PilastriAcciaio",
        "c0302_pilastro_interno": "PilastriAcciaio",
        "mineralized wood ceiling block": "ControsoffittoLegno",
        "g0402_rivestimento_di_soffitti": "ControsoffittoLegno",
        "stainless steel sink": "Terminali",
        "d0805_acqua_rubinetteria_apparecchio": "Terminali",
        "painted terracotta floor tile": "PavCeramica",
        "g0202_pavimento": "PavCeramica",
    }

    SEVERITY_MAP = {
        "M": "Minor",
        "S": "Serious",
        "G": "Severe"
    }

    def __init__(self, db_path: Path = DB_PATH):
        if not db_path.exists():
            init_db()
        self.conn = sqlite3.connect(db_path)
        self.conn.row_factory = sqlite3.Row
        self.component_map = {self._normalize(k): v for k, v in self.RAW_COMPONENT_MAP.items()}

    def _normalize(self, text: str) -> str:
        return re.sub(r"[^a-zA-Z0-9]", "", str(text or "")).lower()

    def resolve_component_key(self, raw_component: str) -> str:
        norm = self._normalize(raw_component)
        if norm in self.component_map:
            return self.component_map[norm]

        for k, v in self.component_map.items():
            if k in norm or norm in k:
                return v

        cursor = self.conn.cursor()
        cursor.execute("SELECT DISTINCT nome_foglio FROM rsl_catalog")
        rows = [r[0] for r in cursor.fetchall() if r[0]]
        for foglio in rows:
            fnorm = self._normalize(foglio)
            if fnorm in norm or norm in fnorm:
                return foglio
        return raw_component

    def get_wbs_and_rsl(self, component_name: str) -> Tuple[Optional[str], Optional[int], str]:
        resolved_foglio = self.resolve_component_key(component_name)
        cursor = self.conn.cursor()

        cursor.execute("""
            SELECT codice_wbs, rsl_anni, nome_foglio 
            FROM rsl_catalog 
            WHERE nome_foglio = ? COLLATE NOCASE
            LIMIT 1
        """, (resolved_foglio,))
        row = cursor.fetchone()

        if row:
            return row["codice_wbs"], int(row["rsl_anni"]), row["nome_foglio"]
        return None, None, resolved_foglio

    def match_anomaly(self, codice_wbs: str, observed_defect: str) -> AnomalyEvaluation:
        cursor = self.conn.cursor()
        cursor.execute("""
            SELECT nome_anomalia, codice_anomalia, gravita, descrizione
            FROM anomalie_catalog
            WHERE codice_wbs = ?
        """, (codice_wbs,))
        candidates = cursor.fetchall()

        obs_lower = observed_defect.lower()
        best_match = None

        for cand in candidates:
            nome = cand["nome_anomalia"].lower()
            desc = cand["descrizione"].lower()

            if any(k in obs_lower for k in ["graff", "scratch", "abrasion"]) and (
                "graffiature" in desc or "abrasion" in desc or "graffiti" in desc or "finiture" in nome
            ):
                best_match = cand
                break
            if any(k in obs_lower for k in ["graffiti", "marker", "scritte"]) and ("graffiti" in desc or "scritte" in desc):
                best_match = cand
                break
            if any(k in obs_lower for k in ["rust", "ruggine", "corros", "oxid"]) and ("corrosione" in nome or "ruggine" in desc):
                best_match = cand
                break
            if any(k in obs_lower for k in ["peel", "paint", "vernice", "sfogliam"]) and ("vernice" in desc or "finiture" in nome):
                best_match = cand
                break
            if any(k in obs_lower for k in ["crack", "fessur", "rottur"]) and ("fessur" in nome or "rottur" in nome):
                best_match = cand
                break

        if not best_match and candidates:
            for cand in candidates:
                cand_words = [w for w in cand["nome_anomalia"].lower().split() if len(w) > 3]
                if any(w in obs_lower for w in cand_words):
                    best_match = cand
                    break

        if best_match:
            sev = best_match["gravita"]
            return AnomalyEvaluation(
                observed_defect=observed_defect,
                matched_anomalia_name=best_match["nome_anomalia"],
                codice_anomalia=best_match["codice_anomalia"],
                severity=sev,
                severity_label=self.SEVERITY_MAP.get(sev, "Minor"),
                description=best_match["descrizione"]
            )

        return AnomalyEvaluation(
            observed_defect=observed_defect,
            matched_anomalia_name="Deterioramento generico",
            codice_anomalia="GEN_01",
            severity="M",
            severity_label="Minor",
            description="Visual defect observed without exact SUPSI catalog match."
        )

    def evaluate(
        self,
        component_name: str,
        observed_anomalies: List[str],
        installation_year: Optional[int] = None,
        image_stem: str = "unknown",
        component_id: str = "comp_01",
        ebkp_h_first: Optional[str] = None,
        ebkp_h_second: Optional[str] = None,
        ebkp_h_third: Optional[str] = None,
        geometry: Optional[str] = None,
        geometry_metric_measured: Optional[Dict[str, float]] = None,
        aesthetics: Optional[str] = None,
        functionality: Optional[str] = None,
        pollutants: Optional[str] = None,
        connection_type: Optional[str] = None,
        disassembly_difficulty: Optional[str] = None,
        bounding_box_2d: Optional[List[int]] = None
    ) -> ComponentCircularityReport:
        lookup_candidates = [ebkp_h_third, component_name]
        wbs, rsl, foglio = None, None, component_name
        for cand in lookup_candidates:
            if cand:
                w, r, f = self.get_wbs_and_rsl(cand)
                if w:
                    wbs, rsl, foglio = w, r, f
                    break

        if not rsl:
            rsl = 30

        age = None
        res_life = None
        if installation_year:
            age = CURRENT_YEAR - installation_year
            res_life = max(0, rsl - age)

        eval_anomalies = []
        highest_severity = "M"
        for defect in observed_anomalies:
            res = self.match_anomaly(wbs or "", str(defect))
            eval_anomalies.append(res)
            if res.severity == "G":
                highest_severity = "G"
            elif res.severity == "S" and highest_severity != "G":
                highest_severity = "S"

        if highest_severity == "G":
            reuse_tier = "Recycling / Material Recovery (Severe Defect)"
        elif res_life is not None and res_life >= 15 and highest_severity == "M":
            reuse_tier = "High Reuse Value (Direct Reuse / Refurbish)"
        elif res_life is not None and res_life > 0:
            reuse_tier = "Medium Reuse Value (Refurbish Required)"
        else:
            reuse_tier = "Recycling (End of Technical Life)"

        # Prefer metric measurement if available over rough VLM text estimate
        final_geometry = geometry
        if geometry_metric_measured:
            w = geometry_metric_measured.get("width_m")
            h = geometry_metric_measured.get("height_m")
            t = geometry_metric_measured.get("thickness_m")
            if w and h:
                final_geometry = f"{w:.2f} m x {h:.2f} m (measured via Metric Depth)"
                if t:
                    final_geometry += f" x {t:.2f} m"

        return ComponentCircularityReport(
            image_stem=image_stem,
            component_id=component_id,
            component_name=component_name,
            matched_foglio=foglio,
            codice_wbs=wbs or "UNKNOWN",
            theoretical_rsl=rsl,
            installation_year=installation_year,
            age_years=age,
            residual_service_life=res_life,
            reuse_tier_evaluation=reuse_tier,
            anomalies=eval_anomalies,
            ebkp_h_first=ebkp_h_first,
            ebkp_h_second=ebkp_h_second,
            ebkp_h_third=ebkp_h_third,
            geometry=final_geometry,
            geometry_metric_measured=geometry_metric_measured,
            aesthetics=aesthetics,
            functionality=functionality,
            pollutants=pollutants,
            connection_type=connection_type,
            disassembly_difficulty=disassembly_difficulty,
            bounding_box_2d=bounding_box_2d
        )


