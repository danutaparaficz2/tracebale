# Directory Reader for vLLM Outputs
# ---------------------------------------------------------------------------
def process_all_vllm_outputs(
    output_dir: Path = HERE / "vllm_output",
    image_dir: Optional[Path] = None,
    depth_model: Optional[Any] = None,
    install_year_map: Optional[Dict[str, int]] = None,
    default_install_year: Optional[int] = 2011
) -> List[ComponentCircularityReport]:
    """Reads all vLLM JSON files, optionally measures metric size via depth model, and returns reports."""
    engine = SupsiRuleEngine()
    json_files = sorted(Path(output_dir).glob("*.json"))

    if not json_files:
        print(f"No JSON files found in {output_dir}")
        return []

    reports = []
    install_map = install_year_map or {}

    for jf in json_files:
        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except Exception as e:
            print(f"Skipping {jf.name} due to parse error: {e}")
            continue

        image_stem = jf.stem
        inst_year = install_map.get(image_stem, default_install_year)

        components = data.get("components") or data.get("salvageable_components", [])

        for idx, comp in enumerate(components, 1):
            comp_id = comp.get("component_id", f"comp_{idx:02d}")
            comp_name = comp.get("component_name") or comp.get("item_name", "Unknown Element")

            ebkp = comp.get("ebkp_h_classification", {})
            first_level = ebkp.get("first_level")
            second_level = ebkp.get("second_level")
            third_level = ebkp.get("third_level_code")

            conds = comp.get("conditions", {})
            aesthetics = conds.get("aesthetics_condition")
            functionality = conds.get("functionality_condition")
            pollutants = conds.get("pollutants_flag")
            if not pollutants and "hazard_and_diagnostic_flags" in data:
                pollutants = "Likely" if data["hazard_and_diagnostic_flags"] else "Unlikely"

            disasm = comp.get("disassembly", {})
            conn_type = disasm.get("connection_type") or comp.get("technical_features", {}).get("connection_type")
            difficulty = disasm.get("difficulty")

            anomalies = comp.get("observed_anomalies", [])
            if not anomalies and "hazard_and_diagnostic_flags" in data:
                anomalies = data["hazard_and_diagnostic_flags"]

            geom = comp.get("geometry_estimate")
            bbox = comp.get("bounding_box_2d")

            metric_meas = None
            if depth_model is not None and image_dir is not None and bbox:
                # Find matching image file
                for ext in [".jpg", ".jpeg", ".png", ".HEIC"]:
                    img_cand = Path(image_dir) / f"{image_stem}{ext}"
                    if img_cand.exists():
                        try:
                            from estimate_metric import estimate_component_size
                            metric_meas = estimate_component_size(str(img_cand), bbox, depth_model)
                        except Exception as err:
                            print(f"Could not calculate metric depth for {image_stem}: {err}")
                        break

            report = engine.evaluate(
                component_name=comp_name,
                observed_anomalies=anomalies,
                installation_year=inst_year,
                image_stem=image_stem,
                component_id=comp_id,
                ebkp_h_first=first_level,
                ebkp_h_second=second_level,
                ebkp_h_third=third_level,
                geometry=geom,
                geometry_metric_measured=metric_meas,
                aesthetics=aesthetics,
                functionality=functionality,
                pollutants=pollutants,
                connection_type=conn_type,
                disassembly_difficulty=difficulty,
                bounding_box_2d=bbox
            )
            reports.append(report)

    return reports


# ---------------------------------------------------------------------------
# Excel Exporter (Mirrors 261013_Inventory_example.xlsx)
# ---------------------------------------------------------------------------
def export_reports_to_excel(
    reports: List[ComponentCircularityReport],
    output_excel_path: Path = Path("TRACEABLE_Inventory_AI_Generated.xlsx")
):
    """Exports evaluated components into an Excel file directly matching SUPSI's inventory schema."""
    rows = []
    for r in reports:
        anomalies_str = "; ".join([f"{a.observed_defect} -> {a.matched_anomalia_name} ({a.severity_label})" for a in r.anomalies])
        rows.append({
            "code images": r.image_stem,
            "First level": r.ebkp_h_first or "",
            "Second level": r.ebkp_h_second or "",
            "Third level": r.ebkp_h_third or "",
            "Component name": r.component_name,
            "Codice WBS": r.codice_wbs,
            "Installation period": r.installation_year or "",
            "Service life (years)": r.theoretical_rsl,
            "Residual Life (years)": r.residual_service_life or "",
            "Reuse Tier": r.reuse_tier_evaluation,
            "Geometry": r.geometry or "",
            "Aesthetics": r.aesthetics or "",
            "Functionality": r.functionality or "",
            "Presence of pollutants": r.pollutants or "",
            "Connection type": r.connection_type or "",
            "Difficulty": r.disassembly_difficulty or "",
            "Observed Anomalies": anomalies_str,
            "Bounding Box": str(r.bounding_box_2d) if r.bounding_box_2d else ""
        })

    df = pd.DataFrame(rows)
    df.to_excel(output_excel_path, index=False, sheet_name="Inventory")
    print(f"Exported {len(rows)} evaluated components to: {output_excel_path}")


# ---------------------------------------------------------------------------
# Command Line Interface & Main Runner
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="TRACEABLE Knowledge Base & Rule Engine")
    parser.add_argument("--vllm-dir", default=str(HERE / "vllm_output"),
                        help="Directory containing vLLM JSON files")
    parser.add_argument("--image-dir", default=None,
                        help="Directory containing RGB images (optional, triggers metric depth estimation)")
    parser.add_argument("--depth-weights", default=None,
                        help="Path to Depth Anything V2 metric checkpoint (optional)")
    parser.add_argument("--export-excel", default="TRACEABLE_Inventory_AI_Generated.xlsx",
                        help="Target Excel file path for the evaluated inventory")
    parser.add_argument("--rebuild-db", action="store_true", help="Force rebuild of SQLite database")
    args = parser.parse_args()

    init_db(force_rebuild=args.rebuild_db)

    depth_model = None
    if args.depth_weights and Path(args.depth_weights).exists():
        try:
            from estimate_metric import load_metric_depth_model
            print(f"Loading Depth Anything V2 model from {args.depth_weights}...")
            depth_model = load_metric_depth_model(checkpoint_path=args.depth_weights)
        except Exception as e:
            print(f"Notice: Metric depth model could not be loaded: {e}")

    vllm_path = Path(args.vllm_dir)
    if vllm_path.is_dir():
        print(f"Processing vLLM outputs from: {vllm_path}")
        reports = process_all_vllm_outputs(
            output_dir=vllm_path,
            image_dir=Path(args.image_dir) if args.image_dir else None,
            depth_model=depth_model
        )
        print(f"Evaluated {len(reports)} component(s).")

        for r in reports:
            print(f"\n[{r.image_stem}] {r.component_name}")
            print(f"  WBS: {r.codice_wbs} | RSL: {r.theoretical_rsl} yrs | ResLife: {r.residual_service_life} yrs")
            print(f"  Geometry: {r.geometry}")
            print(f"  Reuse Tier: {r.reuse_tier_evaluation}")
            for a in r.anomalies:
                print(f"    - Anomaly: {a.observed_defect} -> {a.matched_anomalia_name} (Severity {a.severity})")

        export_reports_to_excel(reports, Path(args.export_excel))
    else:
        print(f"Directory {vllm_path} not found. Running built-in self test...")
        engine = SupsiRuleEngine()
        rep = engine.evaluate(
            component_name="flush steel fire-rated door leaf",
            observed_anomalies=["Graffi superficiali e scritte con marker"],
            installation_year=2011,
            ebkp_h_third="G0105_Porta_interna"
        )
        print(f"Self-test output: {rep.component_name} -> WBS {rep.codice_wbs}, Residual Life: {rep.residual_service_life} yrs")


if __name__ == "__main__":
    main()
